#!/usr/bin/env node
/**
 * LiveDrop — Create a test seller account (run by the project owner).
 *
 * Signs up a seller through the normal self-registration path (anon key), so the
 * auth trigger provisions the profile exactly as the seller app would. The seller
 * starts UNAPPROVED; the script prints the one SQL line to approve it in the
 * Supabase SQL editor. Credentials are generated locally and written to a
 * git-ignored file — they are never printed.
 *
 * Usage:
 *   TEST_SELLER_EMAIL=you+seller@gmail.com TEST_SELLER_PHONE=98XXXXXXXX \
 *     node scripts/create-test-seller.mjs
 *
 * Required:
 *   TEST_SELLER_EMAIL   An inbox you control (a +alias works) in case email confirmation is on.
 *   TEST_SELLER_PHONE   10-digit Indian mobile you control; buyers' "Chat with Boutique" opens it.
 *
 * Optional:
 *   SUPABASE_URL / SUPABASE_ANON_KEY   Defaults to NEXT_PUBLIC_* values in buyer-web/.env.local.
 *   TEST_STORE_NAME     Defaults to "LiveDrop Atelier".
 *   --force             Overwrite an existing scripts/.env.test-seller.local.
 *
 * Safety: the payee UPI ID is deliberately unpayable (`livedrop.test@livedrop` has no
 * real PSP handle), so a real buyer cannot send money to this test store.
 */

import { createRequire } from 'node:module';
import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.resolve(__dirname, '../buyer-web/package.json'));
const { createClient } = require('@supabase/supabase-js');

const CREDENTIALS_FILE = path.resolve(__dirname, '.env.test-seller.local');
const TEST_UPI_ID = 'livedrop.test@livedrop';

function readBuyerWebEnv() {
  const envPath = path.resolve(__dirname, '../buyer-web/.env.local');
  if (!fs.existsSync(envPath)) return {};
  const values = {};
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^["']|["']$/g, '');
  }
  return values;
}

function fail(message) {
  console.error(`❌ ${message}`);
  process.exit(1);
}

const buyerEnv = readBuyerWebEnv();
const SUPABASE_URL = process.env.SUPABASE_URL || buyerEnv.NEXT_PUBLIC_SUPABASE_URL;
const ANON_KEY = process.env.SUPABASE_ANON_KEY || buyerEnv.NEXT_PUBLIC_SUPABASE_ANON_KEY;
const EMAIL = process.env.TEST_SELLER_EMAIL;
const PHONE = (process.env.TEST_SELLER_PHONE || '').replace(/\D/g, '').replace(/^91(?=\d{10}$)/, '');
const STORE_NAME = process.env.TEST_STORE_NAME || 'LiveDrop Atelier';
const force = process.argv.includes('--force');

if (!SUPABASE_URL || !ANON_KEY) fail('Set SUPABASE_URL and SUPABASE_ANON_KEY (or keep them in buyer-web/.env.local).');
if (!/^https?:\/\//.test(SUPABASE_URL)) fail('SUPABASE_URL must start with http(s)://');
if (/127\.0\.0\.1|localhost/.test(SUPABASE_URL)) fail('SUPABASE_URL points at a local mock; set the hosted project URL.');
if (!EMAIL || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(EMAIL)) fail('Set TEST_SELLER_EMAIL to an inbox you control.');
if (!/^[6-9]\d{9}$/.test(PHONE)) fail('Set TEST_SELLER_PHONE to a 10-digit Indian mobile number you control.');
if (fs.existsSync(CREDENTIALS_FILE) && !force) {
  fail(`${path.relative(process.cwd(), CREDENTIALS_FILE)} already exists. Re-run with --force to replace it.`);
}

const password = crypto.randomBytes(18).toString('base64url');
const client = createClient(SUPABASE_URL, ANON_KEY, { auth: { persistSession: false } });

console.log(`Creating seller "${STORE_NAME}" <${EMAIL}> on ${new URL(SUPABASE_URL).host} ...`);

const { data, error } = await client.auth.signUp({
  email: EMAIL,
  password,
  options: {
    data: {
      store_name: STORE_NAME,
      phone_number: PHONE,
      upi_id: TEST_UPI_ID,
      return_address: 'LiveDrop test seller (not a real address)',
    },
  },
});

if (error) fail(`Sign-up failed: ${error.message}`);
const userId = data.user?.id;
if (!userId) fail('Sign-up returned no user. If this email is already registered, use a different alias.');

fs.writeFileSync(
  CREDENTIALS_FILE,
  [
    '# Generated by scripts/create-test-seller.mjs — git-ignored, do not commit.',
    `SUPABASE_URL=${SUPABASE_URL}`,
    `SUPABASE_ANON_KEY=${ANON_KEY}`,
    `STAGING_SELLER_EMAIL=${EMAIL}`,
    `STAGING_SELLER_PASSWORD=${password}`,
    '',
  ].join('\n'),
  { mode: 0o600 }
);

const needsConfirmation = !data.session;
console.log('✅ Seller account created. Profile is pending approval.');
console.log(`   User ID: ${userId}`);
console.log(`   Login saved to ${path.relative(process.cwd(), CREDENTIALS_FILE)} (git-ignored).`);
console.log('\nNext, in the Supabase SQL editor run:\n');
if (needsConfirmation) {
  console.log(`   update auth.users set email_confirmed_at = now() where id = '${userId}';`);
}
console.log(`   select public.admin_approve_seller('${userId}', true);`);
console.log('\nThen add the live drop and products:\n');
console.log(`   node --env-file=${path.relative(process.cwd(), CREDENTIALS_FILE)} scripts/seed-legitimate-staging-drop.mjs\n`);
